/**
 * ─── Voice cards: how each speaker sounds, and the tone of every line ───────
 *
 * Input for the voice-over pipeline (`tools/voice/`, `pnpm voice:*`), never
 * imported by the game. A card describes a voice the way a voice-design TTS
 * model takes it: a clean, natural HUMAN voice (age, gender, pitch, pace,
 * texture, attitude). The robot sound is never asked of the model: the
 * speaker's FX chain adds it afterwards (`tools/voice/fx.mjs`, ported from the
 * Audacity chains in `story-voice-over.md`), so a cloned voice stays stable.
 *
 * `referenceText` is read once, neutral, to record the frozen reference clip
 * (`vo-src/refs/<speaker>/<lang>.wav`) that every line is cloned from.
 * `TONES` gives each catalogue line one word for engines that steer by a
 * knob rather than by text (Chatterbox's exaggeration, Qwen's reference
 * bank); engines that read text get the line's full direction as well.
 *
 * Atlas "never shouts" (its tense lines are 'urgent'); Vex is "it" in the
 * story but voiced male-coded, to match its chain (−2 semitones + a sub
 * octave); Flux is designed late-teen because its chain pitches it up 3
 * semitones (a child's voice would come out a chipmunk).
 *
 * Pure data, no runtime imports: `tools/` read it with Node's type stripping.
 */

