// `pnpm voice:collect` — every voice line as a TTS job: its English and German
// text (params filled, then normalised for speech), who says it with that
// speaker's voice card, the stage direction, the situation, the tone, the
// longest it may run, and the file the game will read.
//
//   pnpm voice:collect              the lines the game speaks (live)
//   pnpm voice:collect --all        planned lines too (Vex, Flux, Gauss…)
//   pnpm voice:collect --samples    3 lines per language, for comparing engines
//   --lang en|de                    one language only
//
// Writes vo-src/jobs/<live|all|samples>.json (what `voice:gen` reads) and a
// readable .md beside it. A neutral line (barks, laughs) is English only:
// every language plays the English take.

import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { CARDS, LANGS, ROOT, SAMPLE_KEYS, VOICE_LINES, VO_SRC, VOICE_OUT, args, fileName, textOf, toneOf, voiceAliasesOf } from './lib.mjs'
import { normalize } from './normalize.mjs'

/**
 * Respellings for a word the model keeps getting wrong in one line (by job
 * id): the model reads `say`, QA still checks the take against the real text.
 */
/** Lines whose text is broken on purpose (Vex stuttering "per-fect-ly"): a read-back cannot match it. */
const BROKEN = new Set(['vex.hub.volt'])

const SAY = {
  // "Relais" (French, [ʁəˈlɛː]) comes out "Zweiheles" in this two-word exclamation.
  'de/atlas_arc_2': 'Zwei Relä! Vex schmollt.',
  // "Rotorflug" comes out "Roter Pflüg" in every ElevenLabs take, "Rotor-Flug"
  // too: two words, the long o's spelled out.
  'de/atlas_story_rotor': 'Rohtohr Fluhg. Wind in meiner Antenne!',
  // "Labor" came out English ("LAY-bor"), then "Laboor" as "LAAA-bor" (#179):
  // two words, so the stress lands on "Bohr" (as in Niels Bohr), the German way.
  'de/atlas_debrief_toLab': 'Ab ins La Bohr.',
  'de/pip_debrief_go': 'Rüste dich aus, dann los! Ich hüte das La Bohr.',
  // "Diagnose" came out English ("DIE-ag-nose", #179): the long German o
  // keeps the word German (Whisper hears German in it, no longer English).
  'de/story_vex_diagnosis': 'Diagnohse: Dieses Tal ist Krank. Die Heilung... bin Ich!',
  // Barks the model spells out as letters or pads with words: a pronounceable sound instead.
  ...Object.fromEntries([1, 2, 3].flatMap(n => [
    [`en/flux_hurt_lowHp_${n}`, 'Unnngh!'],
    [`en/flux_hurt_pit_${n}`, 'Whaaaaaa!'],
    [`en/flux_hurt_wind_${n}`, 'Whoa, whoa, whoa!']
  ])),
  'en/flux_hurt_ice_1': 'Brrrr!',
  'en/flux_hurt_ice_3': 'Brrrr! Zzt!'
}

/**
 * Respellings for a word the model gets wrong in every line it is in, per
 * language: applied to what the model reads (`say`) only, never to the
 * subtitle. QA still checks the take against the real text.
 */
const WORDS = {
  de: [
    // "Blocke" ([ˈblɔkə]) comes out "Bloooke" (Whisper hears "Bloke"), worst
    // at the start of a line. "Blokke", "Blockeh" and "Blockuh" don't help (or
    // turn the k into "Bloche"), an IPA phoneme tag is read out as text; a
    // written schwa keeps the o short. "blocken" comes out right as it is.
    [/\b([Bb])locke\b/g, '$1lockə']
  ]
}

/** `text` with the language's word respellings, or null when none applies. */
const respell = (text, lang) => {
  let out = text
  for (const [from, to] of WORDS[lang] ?? []) out = out.replace(from, to)
  return out === text ? null : out
}

const a = args()
const mode = a.samples ? 'samples' : a.all ? 'all' : 'live'
const langs = a.lang ? [a.lang] : LANGS
if (langs.some(l => !LANGS.includes(l))) throw new Error(`--lang must be one of ${LANGS.join(', ')}`)

/** What the model reads for a line: the normalised text with its respellings. */
const spoken = (line, lang) => {
  const shown = textOf(line, lang)
  if (!shown || /\{\w+\}/.test(shown)) return null
  const { text } = normalize(shown, lang)
  const file = fileName(line.key)
  return respell(SAY[`${lang}/${file}`] ?? text, lang) ?? SAY[`${lang}/${file}`] ?? text
}

// One recording per sentence: a line with the same speaker, language and words
// as another plays that one's file (src/game/audio/voiceAliases.ts, read by
// audio/voice.ts), so it is never voiced twice. `distinct` in the catalogue
// opts a line out (random bark takes, a laugh read three ways).
const hasFile = (lang, file) => existsSync(join(VOICE_OUT, lang, `${file}.ogg`))
const ALIASES = voiceAliasesOf(VOICE_LINES.filter(l => l.status === 'live'), LANGS, spoken, hasFile)
const aliasFile = join(ROOT, 'src/game/audio/voiceAliases.ts')
const block = (map) => {
  const rows = Object.entries(map).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`)
  return rows.length ? `{\n${rows.join(',\n')}\n  }` : '{}'
}
writeFileSync(aliasFile, [
  '// Generated by `pnpm voice:collect` (voiceAliasesOf in voiceCatalog.ts): do not edit by hand.',
  '// Per voiced language, a line that says the same words as another → the line whose file it plays.',
  'export const VOICE_ALIASES: Readonly<Record<string, Readonly<Record<string, string>>>> = {',
  LANGS.map(l => `  ${JSON.stringify(l)}: ${block(ALIASES[l])}`).join(',\n'),
  '}',
  ''
].join('\n'))
const redundant = LANGS.flatMap(l => Object.keys(ALIASES[l]).map(k => `${l}/${fileName(k)}.ogg`).filter(f => existsSync(join(VOICE_OUT, f))))

const pick = mode === 'samples'
  ? SAMPLE_KEYS.map(k => VOICE_LINES.find(l => l.key === k) ?? (() => { throw new Error(`sample ${k} is not in the catalogue`) })())
  : VOICE_LINES.filter(l => mode === 'all' || l.status === 'live')

const jobs = []
const skipped = []
for (const line of pick) {
  for (const lang of langs) {
    const shown = textOf(line, lang)
    if (!shown) continue
    if (ALIASES[lang]?.[line.key]) continue // plays its twin's file
    if (/\{\w+\}/.test(shown)) { skipped.push(`${lang} ${line.key}: unfilled ${shown.match(/\{\w+\}/)[0]}`); continue }
    const { text, emphasis } = normalize(shown, lang)
    const file = fileName(line.key)
    jobs.push({
      id: `${lang}/${file}`,
      key: line.key,
      file,
      lang,
      speaker: line.speaker,
      scene: line.scene,
      status: line.status,
      tone: toneOf(line),
      max: line.max,
      shown,
      text,
      ...((say => say ? { say } : {})(respell(SAY[`${lang}/${file}`] ?? text, lang) ?? SAY[`${lang}/${file}`])),
      // A sound, not words (barks, laughs), or a word broken on purpose: QA does not check it against the text.
      ...(line.neutral || line.loose || BROKEN.has(line.key) ? { loose: true } : {}),
      emphasis,
      // The catalogue writes directions in English and German; a later language
      // takes the English one (Chatterbox steers by the tone alone anyway).
      direction: line.direction[LANGS.indexOf(lang)] ?? line.direction[0],
      // For engines that take the direction as an English tag whatever the line's language.
      directionEn: line.direction[0],
      situation: line.when[LANGS.indexOf(lang)] ?? line.when[0],
      out: relative(ROOT, join(VOICE_OUT, lang, `${file}.ogg`)).replaceAll('\\', '/')
    })
  }
}

const speakers = [...new Set(jobs.map(j => j.speaker))]
const doc = {
  mode,
  langs,
  cards: Object.fromEntries(speakers.map(s => [s, CARDS[s]])),
  jobs
}
const dir = join(VO_SRC, 'jobs')
mkdirSync(dir, { recursive: true })
writeFileSync(join(dir, `${mode}.json`), `${JSON.stringify(doc, null, 2)}\n`)

const cell = (s) => String(s).replaceAll('|', '\\|')
const md = [`# Voice jobs: ${mode}`, '', `Generated by \`pnpm voice:collect${mode === 'live' ? '' : ` --${mode}`}\`. ${jobs.length} jobs.`, '',
  '| Id | Speaker | Tone | Max s | Text for the model | Direction | Situation |', '| --- | --- | --- | --- | --- | --- | --- |',
  ...jobs.map(j => `| ${j.id} | ${j.speaker} | ${j.tone} | ${j.max} | ${cell(j.text)} | ${cell(j.direction)} | ${cell(j.situation)} |`)]
writeFileSync(join(dir, `${mode}.md`), `${md.join('\n')}\n`)

const per = langs.map(l => `${l} ${jobs.filter(j => j.lang === l).length}`).join(', ')
console.log(`vo-src/jobs/${mode}.json: ${jobs.length} jobs (${per}), speakers ${speakers.join(', ')}`)
for (const s of skipped) console.warn(`  skipped ${s}`)
const aliased = LANGS.map(l => `${l} ${Object.keys(ALIASES[l]).length}`).join(', ')
console.log(`src/game/audio/voiceAliases.ts: lines that play a twin's file (${aliased})`)
for (const f of redundant) console.warn(`  redundant: public/audio/voice/${f} (its twin's file plays instead; delete it)`)
